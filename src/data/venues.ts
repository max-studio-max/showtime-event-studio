export const venueEvidence: SourceEvidence[] = [];

function ev(venueId: string, fieldPath: string, value: string | number | null, url: string, publisher: string, unit?: string, notes?: string): string {
  const id = `ev-${venueId}-${fieldPath.replace(/[^a-z0-9]+/gi, '-')}`;
  venueEvidence.push({
    id,
    entityType: 'venue',
    entityId: venueId,
    fieldPath,
    assertedValue: value,
    unit,
    sourceType: 'official_venue_website',
    sourceUrl: url,
    publisher,
    retrievedAt: RETRIEVED,
    extractionMethod: METHOD,
    reviewerId: null,
    verificationStatus: 'third_party_unverified',
    confidenceClass: 'medium',
    usagePolicy: 'Link to original only; do not copy venue documents or drawings without permission',
    notes,
  });
  return id;
}

